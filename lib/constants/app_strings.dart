// ── Translation extension ─────────────────────────────────────────────────────
extension TrContext on BuildContext {
  String tr(String key) {
    final code = watch<SettingsProvider>().locale.languageCode;
    return AppStrings.get(key, code);
  }

  // Dynamic strings: context.trArgs('threshold', {'value':'6000','unit':'RPM'})
  String trArgs(String key, Map<String, String> args) {
    String result = tr(key);
    args.forEach((k, v) => result = result.replaceAll('{$k}', v));
    return result;
  }

  bool get isRtl => AppStrings.rtlLanguages
      .contains(watch<SettingsProvider>().locale.languageCode);
}

// ── RTL-safe Text widget (never use const with tr()) ─────────────────────────
class TrText extends StatelessWidget {
  final String trKey;
  final TextStyle? style;
  final TextAlign? textAlign;
  final int? maxLines;
  final TextOverflow? overflow;
  const TrText(this.trKey,
      {super.key, this.style, this.textAlign, this.maxLines, this.overflow});

  @override
  Widget build(BuildContext context) => Text(
        context.tr(trKey),
        style: style,
        textAlign: textAlign,
        maxLines: maxLines,
        overflow: overflow ?? TextOverflow.ellipsis,
      );
}

